```php
<?php

/*
|--------------------------------------------------------------------------
| Session Start
|--------------------------------------------------------------------------
*/

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

/*
|--------------------------------------------------------------------------
| Default Language
|--------------------------------------------------------------------------
*/

if (!isset($_SESSION['language'])) {
    $_SESSION['language'] = 'en';
}

/*
|--------------------------------------------------------------------------
| Language Change
|--------------------------------------------------------------------------
*/

if (isset($_GET['lang'])) {

    $lang = $_GET['lang'];

    if ($lang === 'ps' || $lang === 'en') {
        $_SESSION['language'] = $lang;
    }

    header("Location: dashboard.php");
    exit();
}

/*
|--------------------------------------------------------------------------
| Load Translation File
|--------------------------------------------------------------------------
*/

if ($_SESSION['language'] === 'ps') {

    $translations = require __DIR__ . '/language/ps.php';

} else {

    $translations = require __DIR__ . '/language/en.php';

}

/*
|--------------------------------------------------------------------------
| Translation Function
|--------------------------------------------------------------------------
*/

function __($key)
{
    global $translations;

    return $translations[$key] ?? $key;
}

?>
```
